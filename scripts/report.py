"""Write the data exploration and entity-resolution report.

docs/data_exploration.md holds aggregates only (committed). Row-level logs go to
data/processed/resolution/ (gitignored: they are derived from tennis-data's copyrighted files).
"""

from pathlib import Path

import pandas as pd

from scripts import resolve, sackmann, tennis_data

DOC = Path("docs/data_exploration.md")
LOG_DIR = Path("data/processed/resolution")


def table(frame: pd.DataFrame) -> str:
    """Render a DataFrame as a GitHub Markdown table."""
    frame = frame.reset_index()
    head = "| " + " | ".join(map(str, frame.columns)) + " |"
    rule = "| " + " | ".join("---" for _ in frame.columns) + " |"
    rows = [
        "| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |" for row in frame.itertuples(index=False)
    ]
    return "\n".join([head, rule, *rows])


def bookmaker_coverage(odds: pd.DataFrame) -> pd.DataFrame:
    """Seasons in which each odds prefix prices at least 80% of rows."""
    year = odds["Date"].dt.year
    rows = []
    for prefix in tennis_data.odds_prefixes(odds.columns):
        share = odds[f"{prefix}W"].notna().groupby(year).mean()
        covered = share[share >= 0.8].index
        rows.append(
            {
                "prefix": prefix,
                "kept as": tennis_data.BOOKMAKERS.get(prefix, tennis_data.MARKET.get(prefix, "dropped")),
                "seasons >= 80%": len(covered),
                "first": covered.min() if len(covered) else "",
                "last": covered.max() if len(covered) else "",
            }
        )
    return pd.DataFrame(rows).set_index("prefix").sort_values("seasons >= 80%", ascending=False)


def rank_validation(links: pd.DataFrame, odds: pd.DataFrame, sack: pd.DataFrame) -> pd.DataFrame:
    """Share of links whose two ATP ranks agree across sources, per method (independent check)."""
    joined = links.merge(odds[["oddsRowId", "WRank", "LRank"]], on="oddsRowId").merge(
        sack[["matchId", "winnerRank", "loserRank"]], on="matchId"
    )
    w_td, l_td = pd.to_numeric(joined["WRank"], errors="coerce"), pd.to_numeric(joined["LRank"], errors="coerce")
    has_ranks = w_td.notna() & l_td.notna() & joined["winnerRank"].notna() & joined["loserRank"].notna()
    joined = joined[has_ranks].assign(
        equal=(w_td == joined["winnerRank"]) & (l_td == joined["loserRank"]),
        within5=((w_td - joined["winnerRank"]).abs() <= 5) & ((l_td - joined["loserRank"]).abs() <= 5),
    )
    per_method = joined.groupby("method")
    return per_method.agg(links=("equal", "size"), ranksEqual=("equal", "mean"), within5=("within5", "mean")).round(4)


def write_logs(odds: pd.DataFrame, links: pd.DataFrame) -> None:
    """Row-level logs: every link with its provenance, every unmatched/conflict row."""
    LOG_DIR.mkdir(parents=True, exist_ok=True)
    links.to_csv(LOG_DIR / "links.csv", index=False)
    columns = [
        "oddsRowId",
        "status",
        "Date",
        "Tournament",
        "Series",
        "Round",
        "Winner",
        "Loser",
        "winnerKey",
        "loserKey",
    ]
    odds[odds["status"].isin(["unmatched", "conflict"])][columns].to_csv(LOG_DIR / "unmatched.csv", index=False)


def build(raw: dict, odds: pd.DataFrame, links: pd.DataFrame, load_stats: dict) -> str:
    """Assemble the Markdown report from the loaded frames and resolution results."""
    matches, sack = raw["matches"], raw["sack"]
    odds = odds.assign(year=odds["Date"].dt.year)
    eligible = odds[odds["status"] != "out_of_coverage"]
    rate = (eligible["status"] == "matched").mean()
    stats_cov = matches["w_ace"].notna().mean()
    unmatched = odds[odds["status"] == "unmatched"]
    known = set(sack["winnerKey"]) | set(sack["loserKey"])
    absent = pd.concat(
        [
            unmatched["Winner"][~unmatched["winnerKey"].isin(known)],
            unmatched["Loser"][~unmatched["loserKey"].isin(known)],
        ]
    )
    levels = matches["tourney_level"].map(sackmann.LEVEL_NAMES).value_counts().rename("matches")
    diag = resolve.diagnose(odds, sack)
    out = [
        "# Data exploration and entity resolution",
        "",
        "Generated by `make ingest` (`scripts/report.py`). Aggregates only; row-level logs are in"
        + " `data/processed/resolution/` (gitignored).",
        "",
        "## Sackmann ATP (results, players)",
        "",
        f"- Files read: {raw['files']} yearly match files; {raw['read']:,} matches read, "
        f"**{len(matches):,} in scope** (tour-level G/M/A/F, dated 1991-01-01 or later).",
        f"- Players appearing in scope: {raw['players']:,}; duplicate ids merged: {len(raw['remap'])} "
        f"({', '.join(f'{k} -> {v}' for k, v in raw['remap'].items()) or 'none'}).",
        f"- Walkovers: {int(raw['walkovers']):,}; retirements/defaults: {int(raw['retired']):,}.",
        f"- Per-side serve statistics present: {stats_cov:.1%} of matches.",
        "",
        table(levels.rename_axis("level").to_frame()),
        "",
        "## tennis-data.co.uk (results with bookmaker odds)",
        "",
        f"- {len(odds):,} rows from {odds['sourceFile'].nunique()} yearly files "
        f"({odds['Date'].min():%Y-%m-%d} to {odds['Date'].max():%Y-%m-%d}).",
        "- Odds prefixes and coverage (seasons where the prefix prices at least 80% of rows):",
        "",
        table(bookmaker_coverage(odds)),
        "",
        "## Entity resolution",
        "",
        f"Rules: odds date in [tourney_date, tourney_date + {resolve.WINDOW[1]} days], then names, then "
        "tournament (see `scripts/resolve.py`). Rows after the Sackmann cutoff "
        f"({resolve.SACKMANN_CUTOFF:%Y-%m-%d}) are out of coverage and excluded from the rate.",
        "",
        f"**Match rate (odds side): {rate:.2%}** of {len(eligible):,} in-coverage rows; "
        f"{(odds['status'] == 'out_of_coverage').sum():,} rows out of coverage.",
        "",
        table(links["method"].value_counts().rename("links").to_frame()),
        "",
        "### Independent check: ATP ranks agree across sources",
        "",
        table(rank_validation(links, odds, sack)),
        "",
        "### Per year",
        "",
        table(resolve.rate_table(odds, "year")),
        "",
        "### Per tournament series",
        "",
        table(resolve.rate_table(odds, "Series")),
        "",
        "### What is left unmatched",
        "",
        f"- {diag['exact_names_window_minus2']:,} rows would match with exact names if the window started 2 days "
        "earlier (events starting on Saturday/Sunday; Sackmann dates the Monday). Not applied.",
        f"- {diag['winner_loser_swapped']:,} rows match only with winner and loser swapped (source errors)."
        + " Not applied.",
        "- Names absent from Sackmann (most frequent):",
        "",
        table(absent.value_counts().head(12).rename("rows").rename_axis("tennis-data name").to_frame()),
        "",
        "## Loaded odds",
        "",
        table(pd.DataFrame(load_stats).fillna(0).astype(int).rename_axis("bookmaker")),
        "",
    ]
    return "\n".join(out)
